#!/usr/bin/env python3
"""No Man Sky FM: the ship from above in the battle (the user's sprite) -> build/gen/nms_nave_batalha.h
  assets/nave-batalha.png (nose up, transparent round it), kept at its own size and its own colours: up to 15, a palette
  of its own (RGB565), a nibble a pixel (15: none)."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def main(out):
    src = ROOT / 'assets/nave-batalha.png'
    L = ['#pragma once', '/* generated by tools/gen_nave_batalha.py from assets/nave-batalha.png */', '#include <stdint.h>']
    if not src.exists():
        Path(out).write_text('\n'.join(L + ['#define NMS_NAVE_BATALHA 0']) + '\n')
        return
    from PIL import Image
    im = Image.open(src).convert('RGBA')
    w, h = im.size
    rgb = Image.new('RGB', im.size, (0, 0, 0))
    rgb.paste(im, mask=im.getchannel('A'))
    q = rgb.quantize(colors=15, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()[:45]
    a = im.getchannel('A').load()
    qp = q.load()
    nib = [15 if a[x, y] < 128 else qp[x, y] for y in range(h) for x in range(w)]
    if len(nib) & 1:
        nib.append(15)
    data = [(nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2)]
    c565 = [((pal[i * 3] >> 3) << 11) | ((pal[i * 3 + 1] >> 2) << 5) | (pal[i * 3 + 2] >> 3) for i in range(15)]
    L += ['#define NMS_NAVE_BATALHA 1', f'#define NMS_NBT_W {w}', f'#define NMS_NBT_H {h}',
          'static const uint16_t NMS_NBT_PAL[15] = {' + ', '.join(str(c) for c in c565) + '};',
          f'static const uint8_t NMS_NBT[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        L.append('    ' + ', '.join(str(v) for v in data[i:i + 24]) + ',')
    L.append('};')
    Path(out).write_text('\n'.join(L) + '\n')
    print(f'nave-batalha: {w} x {h}, {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
