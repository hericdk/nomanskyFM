#!/usr/bin/env python3
"""No Man Sky FM: the nebula behind space -> build/gen/nms_nebulosa.h
  assets/nebulosa.png (any size, portrait like the reference) boxed down to 96 x 124, each pixel to the nearest of a few
  tones of the picture (no dither: flat pixel-art patches); each tone is a firmware colour and how solid it is (16ths,
  drawn by ui_game.c through Bayer in 2 x 2 screen cells at any zoom, so the stars show through). The night background is left out. A nibble a pixel."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
W, H = 96, 124
# (the picture's tone, firmware colour 0..9 as gen_nave.PAL, solidity /16); solidity 0 = the night (not drawn)
TONES = [((14, 20, 32), 0, 0), ((20, 33, 46), 0, 0), ((30, 35, 45), 0, 0), ((40, 50, 66), 9, 3), ((28, 44, 78), 9, 5),
         ((40, 66, 112), 9, 7), ((48, 92, 150), 2, 4), ((60, 150, 210), 2, 7), ((88, 56, 132), 4, 4), ((150, 80, 120), 4, 7),
         ((214, 120, 110), 5, 8), ((250, 190, 170), 5, 11), ((255, 245, 240), 1, 9)]

def main(out):
    src = ROOT / 'assets/nebulosa.png'
    lines = ['#pragma once', '/* generated by tools/gen_nebulosa.py from assets/nebulosa.png */', '#include <stdint.h>']
    if not src.exists():
        Path(out).write_text('\n'.join(lines + ['#define NMS_NEBULOSA 0']) + '\n')
        print('nebulosa: no assets/nebulosa.png')
        return
    from PIL import Image
    im = Image.open(src).convert('RGB').resize((W, H), Image.BOX)
    def near(c):
        return min(range(len(TONES)), key=lambda i: sum((a - b) ** 2 for a, b in zip(c, TONES[i][0])))
    idx = [near(im.getpixel((x, y))) for y in range(H) for x in range(W)]
    data = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
    lines += ['#define NMS_NEBULOSA 1', f'#define NMS_NB_W {W}', f'#define NMS_NB_H {H}',
              'static const uint8_t NMS_NB_COL[%d] = {%s};   /* tone -> colour (0..9) */' % (len(TONES), ', '.join(str(t[1]) for t in TONES)),
              'static const uint8_t NMS_NB_A[%d] = {%s};   /* tone -> solidity (16ths) */' % (len(TONES), ', '.join(str(t[2]) for t in TONES)),
              f'static const uint8_t NMS_NB[{len(data)}] = {{']
    for k in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[k:k + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    PAL = [(0, 0, 0), (255, 255, 255), (0, 110, 160), (0, 144, 67), (83, 38, 141), (214, 84, 50),
           (0, 232, 0), (255, 0, 70), (255, 235, 0), (25, 43, 86)]
    B = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
    S = 6                                               # (the preview: as drawn, 6 screen px a pixel, gz 2, on black)
    pv = Image.new('RGB', (W * S, H * S))
    for y in range(H * S):
        for x in range(W * S):
            t = TONES[idx[(y // S) * W + x // S]]
            if B[(y // 2) & 3][(x // 2) & 3] < t[2]:
                pv.putpixel((x, y), PAL[t[1]])
    pv.save(ROOT / 'build/nebulosa-preview.png')
    print(f'nebulosa: {W} x {H}, {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
