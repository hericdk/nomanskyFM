#!/usr/bin/env python3
"""No Man Sky FM: the opening picture -> build/gen/nms_abertura.h
  assets/abertura.png (any size, 16:9 as the reference): the middle 1200 x 1080 of a 1920 x 1080 (scaled the same for other
  sizes, the title kept whole), down to 120 x 108 and padded to 120 x 120 (the top and bottom rows repeated), in the ten
  colours of the firmware (black, white, #006EA0 #009043 #53268D #D65432, #00E800 #FF0046 #FFEB00 #192B56) through ordered dither (Bayer 4 x 4), one
  nibble a pixel (7,200 B). Drawn at 2 x by ui_game.c. No picture: an empty header (the opening skips it)."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
PAL = [(0, 0, 0), (255, 255, 255), (0, 110, 160), (0, 144, 67), (83, 38, 141), (214, 84, 50),   # (ui_game.c g_picture's order)
       (0, 232, 0), (255, 0, 70), (255, 235, 0), (25, 43, 86)]
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
N = 120

def main(out):
    src = ROOT / 'assets/abertura.png'
    lines = ['#pragma once', '/* generated by tools/gen_abertura.py from assets/abertura.png */', '#include <stdint.h>']
    if not src.exists():
        lines.append('#define NMS_ABERTURA 0')
        Path(out).write_text('\n'.join(lines) + '\n')
        print('abertura: no assets/abertura.png')
        return
    from PIL import Image
    im = Image.open(src).convert('RGB')
    w, h = im.size
    cw = min(w, round(h * 1200 / 1080))
    im = im.crop(((w - cw) // 2, 0, (w - cw) // 2 + cw, h)).resize((N, round(N * 1080 / 1200)), Image.LANCZOS)
    pad = (N - im.size[1]) // 2
    full = Image.new('RGB', (N, N))
    full.paste(im, (0, pad))
    for y in range(pad):                                 # the sky up, the ground down
        full.paste(im.crop((0, 0, N, 1)), (0, y))
    for y in range(pad + im.size[1], N):
        full.paste(im.crop((0, im.size[1] - 1, N, im.size[1])), (0, y))
    px = full.load()
    idx = []
    for y in range(N):
        for x in range(N):
            r, g, b = px[x, y]
            d = (BAYER[y & 3][x & 3] - 7.5) * 9         # the ordered dither: a nudge before the nearest colour
            r, g, b = r + d, g + d, b + d
            idx.append(min(range(len(PAL)), key=lambda i: (r - PAL[i][0]) ** 2 * 3 + (g - PAL[i][1]) ** 2 * 4 + (b - PAL[i][2]) ** 2 * 2))
    data = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
    lines += ['#define NMS_ABERTURA 1', f'#define NMS_AB_N {N}', f'static const uint8_t NMS_AB[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    preview = Image.new('RGB', (N, N))
    preview.putdata([PAL[i] for i in idx])
    preview.resize((N * 4, N * 4), Image.NEAREST).save(ROOT / 'build/abertura-preview.png')
    print(f'abertura: {N} x {N}, {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
