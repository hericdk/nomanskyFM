#!/usr/bin/env python3
"""No Man Sky FM: the ship from the side (assets/nave-lado.png, nose to the left, the background transparent) ->
  build/gen/nms_nave_lado.h: the longest side 112, a nibble a pixel (15 transparent). Its own colouring (the ten colours
  by chroma and hue, not the nearest: the cream and greys would go orange and purple): light greys white, mid greys a
  checker of white and deep blue, dark deep blue, darker black; red, dark red a checker of red and black; blue (light
  blue white), yellow, orange. Drawn by ui_game.c at the end of the take-off: flying away from the planet, which falls behind in parallax."""
import sys, colorsys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
MAX = 112

def tone(r, g, b, x, y):
    h = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)[0] * 360
    lum, chroma, ck = (r * 3 + g * 6 + b) / 10, max(r, g, b) - min(r, g, b), (x + y) & 1
    if lum < 40:
        return 0                                         # black (outline)
    if chroma < 56:                                      # cream and greys: white, a checker of white and deep blue, deep blue
        return 1 if lum > 165 else (1 if ck else 9) if lum > 110 else 9 if lum > 60 else 0
    if h >= 290 or h < 20:                               # reds (the dark ones lean to magenta)
        return 7 if lum > 85 else (7 if ck else 0) if lum > 50 else 0
    if h < 45:
        return 5                                         # orange
    if h < 75:
        return 8                                         # yellow
    if 180 <= h < 260:
        return 1 if lum > 180 else 2                     # blue (the engine), its glints white
    if 260 <= h < 290:
        return 4                                         # purple
    return 3

def main(out):
    src = ROOT / 'assets/nave-lado.png'
    lines = ['#pragma once', '/* generated by tools/gen_nave_lado.py from assets/nave-lado.png */', '#include <stdint.h>']
    if not src.exists():
        Path(out).write_text('\n'.join(lines + ['#define NMS_NAVE_LADO 0']) + '\n')
        print('nave-lado: no assets/nave-lado.png')
        return
    from PIL import Image
    im = Image.open(src).convert('RGBA')
    im = im.crop(im.getchannel('A').getbbox())
    w, h = im.size
    w2, h2 = MAX, max(1, round(h * MAX / w))
    im = im.resize((w2, h2), Image.BOX)
    px, idx = im.load(), []
    for y in range(h2):
        for x in range(w2):
            r, g, b, a = px[x, y]
            idx.append(15 if a < 140 else tone(r, g, b, x, y))
    if len(idx) & 1:
        idx.append(15)
    data = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
    lines += ['#define NMS_NAVE_LADO 1', f'#define NMS_NL_W {w2}', f'#define NMS_NL_H {h2}', f'static const uint8_t NMS_NL[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    PAL = [(0, 0, 0), (255, 255, 255), (0, 110, 160), (0, 144, 67), (83, 38, 141), (214, 84, 50),
           (0, 232, 0), (255, 0, 70), (255, 235, 0), (25, 43, 86)]
    prev = Image.new('RGB', (w2, h2))
    prev.putdata([PAL[i] if i < 10 else (40, 40, 40) for i in idx[:w2 * h2]])
    prev.resize((w2 * 8, h2 * 8), Image.NEAREST).save(ROOT / 'build/nave-lado-preview.png')
    print(f'nave-lado: {w2} x {h2}, {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
