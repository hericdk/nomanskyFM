#!/usr/bin/env python3
"""No Man Sky FM: the take-off's first shot (the ship from the side) -> build/gen/nms_decolagem.h
  assets/decolagem.png: 16:9 pixel art (1920 x 1080 as the reference), down to 160 x 90, each pixel the nearest of the ten
  colours (redmean, no dither: it is pixel art), lone pixels to their neighbours' colour (a mode filter), run-length coded: a byte = (run - 1) << 4 | colour,
  runs of 1..16, row after row. Drawn at 2 x (320 x 180) by ui_game.c, the camera panning across it between two black
  bars. No picture: the take-off starts behind the ship."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from gen_nave import PAL, near
ROOT = Path(__file__).resolve().parents[1]
W, H = 160, 90
DITHER = float(sys.argv[2]) if len(sys.argv) > 2 else 4.0   # (the dither's strength)

def main(out):
    src = ROOT / 'assets/decolagem.png'
    lines = ['#pragma once', '/* generated by tools/gen_decolagem.py from assets/decolagem.png */', '#include <stdint.h>']
    if not src.exists():
        Path(out).write_text('\n'.join(lines + ['#define NMS_DECOL 0']) + '\n')
        print('decolagem: no assets/decolagem.png')
        return
    from PIL import Image, ImageEnhance
    im = Image.open(src).convert('RGB')
    w, h = im.size
    ch = round(w * 9 / 16)                               # (16:9 from the middle)
    if ch < h:
        im = im.crop((0, (h - ch) // 2, w, (h - ch) // 2 + ch))
    im = im.resize((W, H), Image.BOX)
    im = ImageEnhance.Contrast(im).enhance(1.1)
    BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
    px, idx = im.load(), []
    for y in range(H):                                   # a light ordered dither: the shades between the ten colours
        for x in range(W):
            r, g, b = px[x, y]
            d = (BAYER[y & 3][x & 3] - 7.5) * DITHER
            idx.append(min(range(len(PAL)), key=lambda i: near(r + d, g + d, b + d, PAL[i])))
    data, i = bytearray(), 0
    while i < len(idx):
        run = 1
        while run < 16 and i + run < len(idx) and idx[i + run] == idx[i]:
            run += 1
        data.append((run - 1) << 4 | idx[i])
        i += run
    lines += ['#define NMS_DECOL 1', f'#define NMS_DC_W {W}', f'#define NMS_DC_H {H}', f'#define NMS_DC_LEN {len(data)}',
              f'static const uint8_t NMS_DC[{len(data)}] = {{']
    for k in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[k:k + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    prev = Image.new('RGB', (W, H))
    prev.putdata([PAL[i] for i in idx])
    prev.resize((W * 4, H * 4), Image.NEAREST).save(ROOT / 'build/decolagem-preview.png')
    print(f'decolagem: {W} x {H}, {len(data)} B (RLE)')

if __name__ == '__main__':
    main(sys.argv[1])
