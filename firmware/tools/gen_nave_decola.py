#!/usr/bin/env python3
"""No Man Sky FM: the take-off, from behind, in frames -> build/gen/nms_nave_decola.h
  assets/decola/nave-decola-0..N.png: the ship rendered from the 3D model (hub/nave3d.html) from behind, its nose rising
  frame by frame (a little roll), on a transparent background. All cut to the box round all of them (so they stay in
  place, one over the other), the longest side 48; each pixel the nearest of the firmware's ten colours (as
  tools/gen_nave.py); a nibble a pixel, 15 transparent. Drawn by ui_game.c g_ship_decola (the take-off film)."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from gen_nave import PAL, near
ROOT = Path(__file__).resolve().parents[1]
MAX = 48

def main(out):
    from PIL import Image, ImageEnhance
    srcs = sorted((ROOT / 'assets/decola').glob('nave-decola-*.png'), key=lambda p: int(p.stem.split('-')[-1]))
    lines = ['#pragma once', '/* generated by tools/gen_nave_decola.py from assets/decola/ */', '#include <stdint.h>']
    if not srcs:
        Path(out).write_text('\n'.join(lines + ['#define NMS_NAVE_DECOLA 0']) + '\n')
        print('nave-decola: no frames')
        return
    ims = [Image.open(p).convert('RGBA') for p in srcs]
    box = None
    for im in ims:                                       # the box round all of them
        b = im.getchannel('A').point(lambda a: 255 if a >= 128 else 0).getbbox()
        if b:
            box = b if not box else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    w, h = box[2] - box[0], box[3] - box[1]
    k = MAX / max(w, h)
    w2, h2 = max(1, round(w * k)), max(1, round(h * k))
    data, prevs = bytearray(), []
    for im in ims:
        im = im.crop(box).resize((w2, h2), Image.LANCZOS)
        a = im.getchannel('A')
        im = ImageEnhance.Contrast(ImageEnhance.Color(im.convert('RGB')).enhance(1.5)).enhance(1.15).convert('RGBA')
        im.putalpha(a)
        px, idx = im.load(), []
        for y in range(h2):
            for x in range(w2):
                r, g, b, al = px[x, y]
                if al < 128:
                    idx.append(15)
                else:
                    lum = (r * 3 + g * 6 + b) // 10
                    idx.append(0 if lum < 50 else min(range(len(PAL)), key=lambda i: near(r, g, b, PAL[i])))
        if len(idx) & 1:
            idx.append(15)
        data += bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
        prevs.append(idx)
    fb = (w2 * h2 + 1) // 2
    lines += ['#define NMS_NAVE_DECOLA 1', f'#define NMS_ND_W {w2}', f'#define NMS_ND_H {h2}', f'#define NMS_ND_N {len(ims)}',
              f'#define NMS_ND_FB {fb}                         /* bytes a frame */', f'static const uint8_t NMS_ND[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    sheet = Image.new('RGB', (w2 * len(ims), h2))
    for f, idx in enumerate(prevs):
        fr = Image.new('RGB', (w2, h2))
        fr.putdata([PAL[i] if i < 10 else (40, 40, 40) for i in idx[:w2 * h2]])
        sheet.paste(fr, (f * w2, 0))
    sheet.resize((sheet.width * 6, h2 * 6), Image.NEAREST).save(ROOT / 'build/nave-decola-preview.png')
    print(f'nave-decola: {len(ims)} frames of {w2} x {h2}, {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
