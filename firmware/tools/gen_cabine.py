#!/usr/bin/env python3
"""No Man Sky FM: inside the ship (assets/cabine.png, square; its window plain white) -> build/gen/nms_cabine.h
  120 x 120 (drawn 2 x by ui_game.c, KNOB 3's last level in space). The window: a paint-bucket fill from inside the white
  (nibble 15: see-through, space shows); the rest coloured by chroma and hue with checkers for the in-between tones (see
  gen_nave_lado.py), tuned for a dark room: navy greys deep blue / black, the lighter ones a checker of deep blue and
  purple, purples purple, reds (the floor, the chair) red and checkers of red and black, cyan lights blue / white.
  RLE: a byte a run (run - 1) << 4 | colour."""
import sys, colorsys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
N = 120

def tone(r, g, b, x, y):
    h = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)[0] * 360
    lum, chroma, ck = (r * 3 + g * 6 + b) / 10, max(r, g, b) - min(r, g, b), (x + y) & 1
    if lum < 30:
        return 0
    if lum > 165 and chroma < 70:
        return 1                                         # white (the console, the keys)
    if lum > 120 and chroma < 70:
        return 1 if ck else 4                            # (its shading)
    if chroma < 40:                                      # the navy greys of the walls
        return 9 if lum < 58 else (9 if ck else 4) if lum < 80 else 4 if lum < 120 else (1 if ck else 4) if lum < 170 else 1
    if 160 <= h < 250:                                   # cyan / blue: the lights, the screens
        return 1 if lum > 160 else 2 if lum > 70 else 9
    if 250 <= h < 325:                                   # purples (the bed)
        return 4 if lum > 45 else (4 if ck else 0)
    if h >= 325 or h < 20:                               # reds (the floor, the chair, the books)
        return 7 if lum > 85 else (7 if ck else 0) if lum > 42 else 0   # (the floor: red and black)
    if h < 45:
        return 5
    if h < 75:
        return 8
    return 3

def main(out):
    src = ROOT / 'assets/cabine.png'
    lines = ['#pragma once', '/* generated by tools/gen_cabine.py from assets/cabine.png */', '#include <stdint.h>']
    if not src.exists():
        Path(out).write_text('\n'.join(lines + ['#define NMS_CABINE 0']) + '\n')
        print('cabine: no assets/cabine.png')
        return
    from PIL import Image, ImageDraw
    im = Image.open(src).convert('RGB')
    W, H = im.size
    win = im.copy()                                      # the window: filled from its middle (the brightest big white)
    seed = max(((x, y) for x in range(W // 20, W, W // 10) for y in range(H // 20, H, H // 10)),
               key=lambda p: (sum(im.getpixel(p)) >= 750, -abs(p[0] - W // 4) - abs(p[1] - H // 3)))
    ImageDraw.floodfill(win, seed, (255, 0, 255), thresh=60)
    mask = Image.new('L', (W, H))
    mask.putdata([255 if c == (255, 0, 255) else 0 for c in win.getdata()])
    sm, mk = im.resize((N, N), Image.BOX), mask.resize((N, N), Image.BOX)
    idx = []
    for y in range(N):
        for x in range(N):
            idx.append(15 if mk.getpixel((x, y)) > 60 else tone(*sm.getpixel((x, y)), x, y))
    data, i = bytearray(), 0
    while i < len(idx):
        j = i
        while j < len(idx) and j - i < 16 and idx[j] == idx[i]:
            j += 1
        data.append(((j - i - 1) << 4) | idx[i])
        i = j
    lines += ['#define NMS_CABINE 1', f'#define NMS_CB_N {N}', f'#define NMS_CB_LEN {len(data)}', f'static const uint8_t NMS_CB[{len(data)}] = {{']
    for k in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[k:k + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    PAL = [(0, 0, 0), (255, 255, 255), (0, 110, 160), (0, 144, 67), (83, 38, 141), (214, 84, 50),
           (0, 232, 0), (255, 0, 70), (255, 235, 0), (25, 43, 86)]
    prev = Image.new('RGB', (N, N))
    prev.putdata([PAL[v] if v < 10 else (60, 200, 60) for v in idx])
    prev.resize((N * 4, N * 4), Image.NEAREST).save(ROOT / 'build/cabine-preview.png')
    print(f'cabine: {N} x {N}, RLE {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
