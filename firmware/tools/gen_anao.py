#!/usr/bin/env python3
"""No Man Sky FM: the character on foot -> build/gen/nms_anao.h
  assets/anao.png: a sheet of 32 x 16 frames (Tiny Clans' axe dwarf, from its Aseprite tags: row 1 idle 8, row 2 walk 8,
  row 3 attack 5). Each frame cut to the dwarf's box and a pixel round it (10 x 11: x 12..21, y 6..16 of the frame),
  its colours to the firmware's (the grey armour white / blue, the darks black / deep blue, brown orange, the skin
  yellow; anything else the nearest), a black outline round it, one nibble a pixel, 15 transparent. Drawn by ui_game.c g_player, facing the way it walks."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from gen_nave import PAL, near
ROOT = Path(__file__).resolve().parents[1]
FW, FH, BX, BY, BW, BH = 32, 16, 12, 6, 10, 11      # (the dwarf's 8 x 9 box and a pixel round it, for the outline)
ROWS = [('IDLE', 0, 8), ('WALK', 1, 8), ('ATK', 2, 5)]
MAP = {(49, 44, 37): 0, (61, 55, 49): 9, (102, 102, 102): 2, (116, 116, 116): 2, (129, 129, 129): 2, (144, 144, 144): 1,
       (168, 168, 168): 1, (183, 183, 183): 1, (69, 48, 24): 5, (93, 65, 34): 5, (231, 213, 179): 8}

def main(out):
    src = ROOT / 'assets/anao.png'
    lines = ['#pragma once', '/* generated by tools/gen_anao.py from assets/anao.png */', '#include <stdint.h>']
    if not src.exists():
        Path(out).write_text('\n'.join(lines + ['#define NMS_ANAO 0']) + '\n')
        print('anao: no assets/anao.png')
        return
    from PIL import Image
    im = Image.open(src).convert('RGBA')
    px, data, first = im.load(), bytearray(), {}
    for name, row, n in ROWS:
        first[name] = len(data) // ((BW * BH + 1) // 2)
        for c in range(n):
            idx = []
            for y in range(BH):
                for x in range(BW):
                    r, g, b, a = px[c * FW + BX + x, row * FH + BY + y] if BY + y < FH else (0, 0, 0, 0)
                    idx.append(15 if a < 128 else MAP.get((r, g, b), min(range(len(PAL)), key=lambda i: near(r, g, b, PAL[i]))))
            idx = [0 if v == 15 and any(0 <= x + u < BW and 0 <= y + w < BH and idx[(y + w) * BW + x + u] != 15
                                        for u, w in ((1, 0), (-1, 0), (0, 1), (0, -1))) else v
                   for y in range(BH) for x in range(BW) for v in [idx[y * BW + x]]]   # a black outline: it reads on any ground
            if len(idx) & 1:
                idx.append(15)
            data += bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
    lines += ['#define NMS_ANAO 1', f'#define NMS_AN_W {BW}', f'#define NMS_AN_H {BH}', f'#define NMS_AN_FB {(BW * BH + 1) // 2}']
    for name, row, n in ROWS:
        lines.append(f'#define NMS_AN_{name} {first[name]}   /* first frame; {n} frames */')
        lines.append(f'#define NMS_AN_{name}_N {n}')
    lines.append(f'static const uint8_t NMS_AN[{len(data)}] = {{')
    for k in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[k:k + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    print(f'anao: {sum(n for _, _, n in ROWS)} frames of {BW} x {BH}, {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
