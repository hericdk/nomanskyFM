#!/usr/bin/env python3
"""No Man Sky FM: the ship of the warp -> build/gen/nms_nave.h
  assets/nave.png: the ship (the warp's one is seen from behind), on a transparent background, or on any plain dark
  background (the colour of the corners is taken as transparent). Fitted into 64 x 64 (the longest side 64, the shape
  kept), each pixel the nearest of the ten
  colours of the firmware (no dither: it is drawn larger, a pixel per block); one nibble a pixel, 15 = transparent.
  Drawn by ui_game.c g_ship_px at any size (the warp grows and shrinks it). No picture: the drawn triangle ship."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
PAL = [(0, 0, 0), (255, 255, 255), (0, 110, 160), (0, 144, 67), (83, 38, 141), (214, 84, 50),
       (0, 232, 0), (255, 0, 70), (255, 235, 0), (25, 43, 86)]
MAX = 64

def near(r, g, b, p):                                    # "redmean": closer to how the eye weighs colours
    rm = (r + p[0]) / 2
    return (2 + rm / 256) * (r - p[0]) ** 2 + 4 * (g - p[1]) ** 2 + (2 + (255 - rm) / 256) * (b - p[2]) ** 2

def main(out, name='nave', P='NMS_NV', ON='NMS_NAVE', MAXS=None):
    """the picture assets/<name>.png -> its header: ON 1, P_W, P_H, P[] (a nibble a pixel, 15 transparent)"""
    global MAX
    if MAXS:
        MAX = MAXS
    src = ROOT / f'assets/{name}.png'
    lines = ['#pragma once', f'/* generated by tools/gen_nave.py from assets/{name}.png */', '#include <stdint.h>']
    if not src.exists():
        Path(out).write_text('\n'.join(lines + [f'#define {ON} 0']) + '\n')
        print(f'{name}: no assets/{name}.png')
        return
    from PIL import Image
    im = Image.open(src).convert('RGBA')
    W, H = im.size
    cs = [im.getpixel(p) for p in ((2, 2), (W - 3, 2), (2, H - 3), (W - 3, H - 3))]
    bg = tuple(sum(c[i] for c in cs) // 4 for i in range(3))   # the background: the corners' colour
    def clear(c):
        return c[3] < 128 or (c[0], c[1], c[2]) == (255, 0, 255) or sum(abs(c[i] - bg[i]) for i in range(3)) < 40
    mask = Image.new('L', im.size)
    mask.putdata([0 if clear(c) else 255 for c in im.getdata()])
    bbox = mask.getbbox()                                # (the background round it off)
    if bbox:
        im = im.crop(bbox)
    w, h = im.size
    k = MAX / max(w, h)
    w2, h2 = max(1, round(w * k)), max(1, round(h * k))
    im = im.resize((w2, h2), Image.NEAREST if max(w, h) <= 64 else Image.LANCZOS)
    from PIL import ImageEnhance                         # (livelier before the ten colours: they are bright)
    a = im.getchannel('A')
    im = ImageEnhance.Contrast(ImageEnhance.Color(im.convert('RGB')).enhance(1.5)).enhance(1.15).convert('RGBA')
    im.putalpha(a)
    px, idx = im.load(), []
    for y in range(h2):
        for x in range(w2):
            r, g, b, a = px[x, y]
            if clear((r, g, b, a)):
                idx.append(15)
            else:
                lum = (r * 3 + g * 6 + b) // 10
                idx.append(0 if lum < 50 else min(range(len(PAL)), key=lambda i: near(r, g, b, PAL[i])))   # (the dark: black outlines)
    if len(idx) & 1:
        idx.append(15)
    data = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
    lines += [f'#define {ON} 1', f'#define {P}_W {w2}', f'#define {P}_H {h2}', f'static const uint8_t {P}[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    prev = Image.new('RGB', (w2, h2))
    prev.putdata([PAL[i] if i < 10 else (40, 40, 40) for i in idx[:w2 * h2]])
    prev.resize((w2 * 8, h2 * 8), Image.NEAREST).save(ROOT / f'build/{name}-preview.png')
    print(f'{name}: {w2} x {h2}, {len(data)} B')

if __name__ == '__main__':
    main(sys.argv[1])
